#!/usr/bin/env node
// Writes internal/importers/unicode_tables.go: character classes JavaScript regexps know and Go's
// regexp does not (\p{Extended_Pictographic}), from the Unicode data in this Node.js.
//
//   node scripts/gen-unicode-tables.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../internal/importers/unicode_tables.go', import.meta.url));
const ranges = (re) => {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp < 0x110000 && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
};
const table = (name, rs) =>
  `var ${name} = &unicode.RangeTable{\n` +
  `\tR16: []unicode.Range16{\n${rs
    .filter(([, b]) => b <= 0xffff)
    .map(([a, b]) => `\t\t{0x${a.toString(16)}, 0x${b.toString(16)}, 1},\n`)
    .join('')}\t},\n` +
  `\tR32: []unicode.Range32{\n${rs
    .filter(([a]) => a > 0xffff)
    .map(([a, b]) => `\t\t{0x${a.toString(16)}, 0x${b.toString(16)}, 1},\n`)
    .join('')}\t},\n}\n`;

const pict = ranges(/^\p{Extended_Pictographic}$/u);
if (pict.some(([a, b]) => a <= 0xffff && b > 0xffff)) throw new Error('range crosses U+FFFF');
writeFileSync(
  OUT,
  `// Code generated by scripts/gen-unicode-tables.mjs from Node.js ${process.versions.node} (Unicode ${process.versions.unicode}); DO NOT EDIT.\n\npackage importers\n\nimport "unicode"\n\n// extendedPictographic is \\p{Extended_Pictographic}.\n${table('extendedPictographic', pict)}`,
);
console.log(`${pict.length} Extended_Pictographic ranges`);
